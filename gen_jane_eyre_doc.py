p('这种结构是 2011 版最大胆、也是影评人讨论最多的改编。好处是节奏紧凑、哥特悬疑感更强；代价是原著中"简爱自述成长"的从容与厚重感被削弱，观众对人物内心的建立更多依赖闪回片段。')

h2('2.2 情节删减与合并')
p('两小时片长无法容纳原著 38 章的容量，电影做了大量取舍：')
bullet('洛伍德学校的"温馨面"被淡化。原著中坦普尔小姐（Miss Temple）善良公正，是简爱的精神支柱；简爱在学校度过了六年学生、两年教师的时光并茁壮成长，这些在电影中几乎只剩"严酷"的一面——勃洛克赫斯特先生当众羞辱、恶劣的伙食与卫生、海伦之死。影评指出几乎所有影视版都倾向突出洛伍德的阴暗，2011 版也不例外。')
bullet('格蕾丝·普尔（Grace Poole）几乎消失。原著中简爱长期怀疑三楼那间房里"疯女人"的看守格蕾丝·普尔是火灾与刺伤事件的元凶，这一悬疑线索铺垫了数十章；电影里她几乎不被提及，仅由阿黛勒提到夜里有一个神秘女人在宅中走动，悬疑的铺陈被大幅压缩。')
bullet('罗切斯特的过去被简化。原著详细交代了他年轻时被父兄安排、与伯莎在牙买加结婚的悲剧，以及他与法国舞女塞丽娜·瓦伦的旧情、阿黛勒的身世；电影只用寥寥数语带过。')
